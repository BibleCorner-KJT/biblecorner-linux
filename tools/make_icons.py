def svg_path(g):
    out = []
    polys = [g] if g.geom_type == 'Polygon' else list(getattr(g, 'geoms', []))
    for p in polys:
        for ring in [p.exterior] + list(p.interiors):
            c = list(ring.coords)
            out.append('M' + ' '.join('%.2f %.2f' % xy for xy in c) + 'Z')
    return ''.join(out)
